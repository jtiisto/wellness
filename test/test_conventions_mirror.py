"""Guard: keep the mirrored conventions modules honest.

`docs/conventions/` holds verbatim copies of modules from the private conventions
repo (a checkout at ``../conventions`` from this repo's root, or
``$CONVENTIONS_DIR``), because a public clone cannot follow a link into a private
repo. The copies are generated by
``../conventions/bin/sync-conventions.sh`` and never edited here. Three checks:

* every copy's sha256 matches ``MANIFEST`` (catches an edit made in this repo);
* when the conventions checkout exists, every copy equals its HEAD (catches a stale
  mirror; skipped in a public clone that has none);
* the Android palette's hex values equal the mirrored token table in both modes,
  so the implementation cannot drift from the authority in either direction.
"""
import hashlib
import os
import pathlib
import re
import subprocess

import pytest

ROOT = pathlib.Path(__file__).resolve().parent.parent
MIRROR = ROOT / "docs" / "conventions"
MANIFEST = MIRROR / "MANIFEST"
def _find_conventions() -> pathlib.Path:
    """$CONVENTIONS_DIR, else the sibling checkout (../conventions — the layout the
    conventions README prescribes). A legacy clone nested one level deeper
    (dev/<product>/<project>) is tolerated so its gate still runs."""
    override = os.environ.get("CONVENTIONS_DIR")
    if override:
        return pathlib.Path(override).resolve()
    for base in (ROOT.parent, ROOT.parent.parent):
        candidate = base / "conventions"
        if (candidate / "universal.md").exists():
            return candidate.resolve()
    return (ROOT.parent / "conventions").resolve()


CONVENTIONS = _find_conventions()
SYNC = CONVENTIONS / "bin" / "sync-conventions.sh"
SYNC_CMD = "../conventions/bin/sync-conventions.sh"
DESIGN = MIRROR / "logbook-design.md"
PALETTE = (
    ROOT / "android" / "core" / "ui" / "src" / "main" / "kotlin" / "dev" / "jtiisto"
    / "wellness" / "core" / "ui" / "theme" / "LogbookPalette.kt"
)

FIX_HINT = (
    "Mirrored files are generated, never edited here: edit the module in "
    f"../conventions, commit there, then run {SYNC_CMD} from this repo's root."
)


def _manifest_entries():
    entries = []
    for raw in MANIFEST.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        assert len(parts) == 3, f"Malformed MANIFEST line: {raw!r}. {FIX_HINT}"
        entries.append(tuple(parts))
    return entries


@pytest.mark.unit
def test_mirror_matches_manifest():
    entries = _manifest_entries()
    assert entries, f"docs/conventions/MANIFEST lists no files. {FIX_HINT}"
    problems = []
    for name, recorded, _commit in entries:
        path = MIRROR / name
        if not path.is_file():
            problems.append(f"{name}: missing from docs/conventions/")
            continue
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        if actual != recorded:
            problems.append(f"{name}: sha256 {actual} != MANIFEST {recorded}")
    assert not problems, "\n".join(problems) + f"\n{FIX_HINT}"


@pytest.mark.unit
def test_mirror_is_current_with_sibling():
    if not (CONVENTIONS / ".git").exists():
        pytest.skip(
            f"no conventions checkout at ../conventions ({CONVENTIONS}; set "
            "CONVENTIONS_DIR to override) — a public clone cannot check staleness "
            "against the authority"
        )
    result = subprocess.run(
        [str(SYNC), "--check"], cwd=ROOT, capture_output=True, text=True,
    )
    assert result.returncode == 0, (
        f"docs/conventions/ is stale against the conventions repo's HEAD — run {SYNC_CMD} "
        f"and commit the refreshed mirror.\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )


_TOKEN_ROW = re.compile(
    r"^\|\s*`(\w+)`\s*\|\s*`(#[0-9A-Fa-f]{6})`\s*\|\s*`(#[0-9A-Fa-f]{6})`\s*\|"
)


def _mirrored_tokens():
    """{token: (light, dark)} from the "## Tokens" table, hex upper-cased."""
    text = DESIGN.read_text()
    section = re.search(r"^## Tokens\n(.*?)(?=^## )", text, re.S | re.M)
    assert section, "docs/conventions/logbook-design.md has no '## Tokens' section"
    tokens = {}
    for line in section.group(1).splitlines():
        m = _TOKEN_ROW.match(line.strip())
        if m:
            tokens[m.group(1)] = (m.group(2).upper(), m.group(3).upper())
    return tokens


def _palette_block(text, name):
    """{token: '#RRGGBB'} from `val <name> = LogbookPalette( ... )`."""
    m = re.search(rf"^val {name} = LogbookPalette\((.*?)^\)", text, re.S | re.M)
    assert m, f"LogbookPalette.kt has no `val {name} = LogbookPalette(` block"
    return {
        token: f"#{hexval.upper()}"
        for token, hexval in re.findall(r"(\w+)\s*=\s*Color\(0xFF([0-9A-Fa-f]{6})\)", m.group(1))
    }


@pytest.mark.unit
def test_palette_matches_mirrored_tokens():
    tokens = _mirrored_tokens()
    assert len(tokens) == 10, f"expected 10 tokens in the mirrored table, parsed {sorted(tokens)}"
    source = PALETTE.read_text()
    light = _palette_block(source, "LogbookLight")
    dark = _palette_block(source, "LogbookDark")

    diffs = []
    for token, (want_light, want_dark) in sorted(tokens.items()):
        for mode, palette, want in (("light", light, want_light), ("dark", dark, want_dark)):
            got = palette.get(token)
            if got != want:
                diffs.append(f"  {token} ({mode}): palette {got or 'missing'} != mirror {want}")
    for mode, palette in (("light", light), ("dark", dark)):
        extra = sorted(set(palette) - set(tokens))
        if extra:
            diffs.append(f"  {mode} palette has tokens the mirror does not: {extra}")
    assert not diffs, (
        "LogbookPalette.kt disagrees with docs/conventions/logbook-design.md:\n"
        + "\n".join(diffs)
        + "\nThe mirror is the authority. Change a value in ../conventions first, then "
        f"run {SYNC_CMD}, then update the palette and re-measure it in LogbookPaletteTest."
    )
