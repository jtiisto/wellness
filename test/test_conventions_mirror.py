"""Guard: keep the mirrored conventions modules honest.

`docs/conventions/` holds verbatim copies of modules from the private conventions
repo (a checkout at ``../conventions`` from this repo's root, or
``$CONVENTIONS_DIR``), because a public clone cannot follow a link into a private
repo. The copies are generated by
``../conventions/bin/sync-conventions.sh`` and never edited here. The checks:

* every copy's sha256 matches ``MANIFEST`` (catches an edit made in this repo);
* when the conventions checkout exists, every copy equals its HEAD (catches a stale
  mirror; skipped in a public clone that has none);
* the Android palette's hex values equal the mirrored token table in both modes,
  so the implementation cannot drift from the authority in either direction;
* the Android Kover gate settings match ``android.md`` (configuration cache off,
  ``--no-build-cache`` on the pre-push gate line) — a rule that lives in project
  files, so a mirrored sentence cannot enforce it; the conventions repo ships the
  check as ``bin/check-android-gate.sh`` and this runs it, with an inline fallback
  for a public clone that has no sibling;
* this project has no pending row in the conventions ``ADOPTION.md`` ledger
  (``bin/check-adoption.sh``; skipped without the sibling), so a rule that needs a
  project change fails the gate until it is adopted.
"""
import hashlib
import os
import pathlib
import re
import subprocess

import pytest

ROOT = pathlib.Path(__file__).resolve().parent.parent
MIRROR = ROOT / "docs" / "conventions"
MANIFEST = MIRROR / "MANIFEST"
def _find_conventions() -> pathlib.Path:
    """$CONVENTIONS_DIR, else the sibling checkout (../conventions — the layout the
    conventions README prescribes). A legacy clone nested one level deeper
    (dev/<product>/<project>) is tolerated so its gate still runs."""
    override = os.environ.get("CONVENTIONS_DIR")
    if override:
        return pathlib.Path(override).resolve()
    for base in (ROOT.parent, ROOT.parent.parent):
        candidate = base / "conventions"
        if (candidate / "universal.md").exists():
            return candidate.resolve()
    return (ROOT.parent / "conventions").resolve()


CONVENTIONS = _find_conventions()
SYNC = CONVENTIONS / "bin" / "sync-conventions.sh"
GATE_CHECK = CONVENTIONS / "bin" / "check-android-gate.sh"
ADOPTION_CHECK = CONVENTIONS / "bin" / "check-adoption.sh"
GRADLE_PROPERTIES = ROOT / "android" / "gradle.properties"
PRE_PUSH = ROOT / "githooks" / "pre-push"
SYNC_CMD = "../conventions/bin/sync-conventions.sh"
DESIGN = MIRROR / "logbook-design.md"
PALETTE = (
    ROOT / "android" / "core" / "ui" / "src" / "main" / "kotlin" / "dev" / "jtiisto"
    / "wellness" / "core" / "ui" / "theme" / "LogbookPalette.kt"
)

FIX_HINT = (
    "Mirrored files are generated, never edited here: edit the module in "
    f"../conventions, commit there, then run {SYNC_CMD} from this repo's root."
)


def _manifest_entries():
    entries = []
    for raw in MANIFEST.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        assert len(parts) == 3, f"Malformed MANIFEST line: {raw!r}. {FIX_HINT}"
        entries.append(tuple(parts))
    return entries


@pytest.mark.unit
def test_mirror_matches_manifest():
    entries = _manifest_entries()
    assert entries, f"docs/conventions/MANIFEST lists no files. {FIX_HINT}"
    problems = []
    for name, recorded, _commit in entries:
        path = MIRROR / name
        if not path.is_file():
            problems.append(f"{name}: missing from docs/conventions/")
            continue
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        if actual != recorded:
            problems.append(f"{name}: sha256 {actual} != MANIFEST {recorded}")
    assert not problems, "\n".join(problems) + f"\n{FIX_HINT}"


@pytest.mark.unit
def test_mirror_is_current_with_sibling():
    if not (CONVENTIONS / ".git").exists():
        pytest.skip(
            f"no conventions checkout at ../conventions ({CONVENTIONS}; set "
            "CONVENTIONS_DIR to override) — a public clone cannot check staleness "
            "against the authority"
        )
    result = subprocess.run(
        [str(SYNC), "--check"], cwd=ROOT, capture_output=True, text=True,
    )
    assert result.returncode == 0, (
        f"docs/conventions/ is stale against the conventions repo's HEAD — run {SYNC_CMD} "
        f"and commit the refreshed mirror.\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )


_TOKEN_ROW = re.compile(
    r"^\|\s*`(\w+)`\s*\|\s*`(#[0-9A-Fa-f]{6})`\s*\|\s*`(#[0-9A-Fa-f]{6})`\s*\|"
)


def _mirrored_tokens():
    """{token: (light, dark)} from the "## Tokens" table, hex upper-cased."""
    text = DESIGN.read_text()
    section = re.search(r"^## Tokens\n(.*?)(?=^## )", text, re.S | re.M)
    assert section, "docs/conventions/logbook-design.md has no '## Tokens' section"
    tokens = {}
    for line in section.group(1).splitlines():
        m = _TOKEN_ROW.match(line.strip())
        if m:
            tokens[m.group(1)] = (m.group(2).upper(), m.group(3).upper())
    return tokens


def _palette_block(text, name):
    """{token: '#RRGGBB'} from `val <name> = LogbookPalette( ... )`."""
    m = re.search(rf"^val {name} = LogbookPalette\((.*?)^\)", text, re.S | re.M)
    assert m, f"LogbookPalette.kt has no `val {name} = LogbookPalette(` block"
    return {
        token: f"#{hexval.upper()}"
        for token, hexval in re.findall(r"(\w+)\s*=\s*Color\(0xFF([0-9A-Fa-f]{6})\)", m.group(1))
    }


@pytest.mark.unit
def test_palette_matches_mirrored_tokens():
    tokens = _mirrored_tokens()
    assert len(tokens) == 10, f"expected 10 tokens in the mirrored table, parsed {sorted(tokens)}"
    source = PALETTE.read_text()
    light = _palette_block(source, "LogbookLight")
    dark = _palette_block(source, "LogbookDark")

    diffs = []
    for token, (want_light, want_dark) in sorted(tokens.items()):
        for mode, palette, want in (("light", light, want_light), ("dark", dark, want_dark)):
            got = palette.get(token)
            if got != want:
                diffs.append(f"  {token} ({mode}): palette {got or 'missing'} != mirror {want}")
    for mode, palette in (("light", light), ("dark", dark)):
        extra = sorted(set(palette) - set(tokens))
        if extra:
            diffs.append(f"  {mode} palette has tokens the mirror does not: {extra}")
    assert not diffs, (
        "LogbookPalette.kt disagrees with docs/conventions/logbook-design.md:\n"
        + "\n".join(diffs)
        + "\nThe mirror is the authority. Change a value in ../conventions first, then "
        f"run {SYNC_CMD}, then update the palette and re-measure it in LogbookPaletteTest."
    )


_GATE_HINT = (
    "The Kover gate must never pass or fail on a cached or random verdict "
    "(docs/conventions/android.md, Coverage): android/gradle.properties sets "
    "org.gradle.configuration-cache=false, and the pre-push gate line runs the root task "
    ":koverVerifyAggregated (leading colon, not the bare name or a module's) with "
    "--no-build-cache."
)

# Same rules as ../conventions/bin/check-android-gate.sh, in explicit ASCII
# classes and the same line model (LF only), so both give the same verdict on
# any NUL-free UTF-8 hook (one that is not UTF-8 fails here; one holding a NUL
# byte is binary to grep and fails in the script). A whole-line comment is
# dropped; a trailing comment ("#" at line start or after a space or tab,
# through end of line) is stripped. Not quote-aware: no hook line needs a "#"
# inside quotes.
_WHOLE_LINE_COMMENT = re.compile(r"[ \t\n\v\f\r]*#")
_TRAILING_COMMENT = re.compile(r"(^|[ \t])#.*")
# The root token: ":koverVerifyAggregated" preceded by start of line, a space or
# a tab, and not followed by [A-Za-z0-9_-] or any non-ASCII character. Each is
# replaced by "." (neither a space nor a name character, so no neighbour changes
# validity); any koverVerifyAggregated left over (bare, a module path such as
# ":app:koverVerifyAggregated", or a longer name) verifies more than the root.
_ROOT_KOVER_VERIFY = re.compile(
    r"(?<![^ \t]):koverVerifyAggregated(?![A-Za-z0-9_\-\u0080-\U0010ffff])"
)


@pytest.mark.unit
def test_android_gate_settings_follow_android_md():
    """The inline check runs everywhere; the shipped script runs where the sibling is."""
    props = GRADLE_PROPERTIES.read_text().splitlines()
    assert any(
        re.fullmatch(r"\s*org\.gradle\.configuration-cache\s*=\s*false\s*", line) for line in props
    ), f"android/gradle.properties does not set org.gradle.configuration-cache=false. {_GATE_HINT}"

    # Bytes decoded without newline translation, split on LF only: the script
    # reads lines the way grep does, so a CR stays part of its line.
    code = [
        _TRAILING_COMMENT.sub(r"\1", line)
        for line in PRE_PUSH.read_bytes().decode("utf-8").split("\n")
        if not _WHOLE_LINE_COMMENT.match(line)
    ]
    gate_lines = [line for line in code if "koverVerifyAggregated" in line]
    assert gate_lines, f"githooks/pre-push has no koverVerifyAggregated gate line. {_GATE_HINT}"
    bare = [line.strip() for line in gate_lines if "--no-build-cache" not in line]
    assert not bare, f"gate line(s) without --no-build-cache: {bare}. {_GATE_HINT}"
    unrooted = [
        line.strip() for line in gate_lines
        if "koverVerifyAggregated" in _ROOT_KOVER_VERIFY.sub(".", line)
    ]
    assert not unrooted, f"gate line(s) not naming the root task: {unrooted}. {_GATE_HINT}"

    if GATE_CHECK.exists():
        result = subprocess.run(
            [str(GATE_CHECK), str(ROOT)], capture_output=True, text=True,
        )
        assert result.returncode == 0, (
            f"../conventions/bin/check-android-gate.sh failed:\n{result.stdout}{result.stderr}"
        )


@pytest.mark.unit
def test_no_pending_adoption_rows():
    if not ADOPTION_CHECK.exists():
        pytest.skip(
            f"no {ADOPTION_CHECK} (a public clone with no conventions sibling, or an "
            "older one) — the adoption ledger cannot be read"
        )
    result = subprocess.run(
        [str(ADOPTION_CHECK), str(ROOT)], capture_output=True, text=True,
    )
    assert result.returncode == 0, (
        f"../conventions/bin/check-adoption.sh reports rules this project has not adopted:\n"
        f"{result.stdout}{result.stderr}"
        "Adopt them in the order docs/conventions/universal.md gives (\"Rules that change "
        "project files\"): make the project change, flip this project's cell in "
        "../conventions/ADOPTION.md, push this project, then commit and push the ledger."
    )
